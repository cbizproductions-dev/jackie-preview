// Packs the built app (dist/) into a Worker module so the deploy is a single script upload.
// Output: src/worker/assets.gen.ts (git-ignored: it contains the bundled header art).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.woff2': 'font/woff2', '.woff': 'font/woff', '.webmanifest': 'application/manifest+json', '.json': 'application/json',
};
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk('dist').filter((f) => !f.endsWith('.woff') || !walk('dist').includes(f.replace(/\.woff$/, '.woff2')));
const out = {};
let bytes = 0;
for (const f of files) {
  const buf = readFileSync(f);
  bytes += buf.length;
  out['/' + relative('dist', f).replace(/\\/g, '/')] = { t: TYPES[extname(f)] ?? 'application/octet-stream', b: buf.toString('base64') };
}
writeFileSync('src/worker/assets.gen.ts', `// Generated by scripts/embed-assets.mjs — do not edit.\nexport const EMBEDDED: Record<string, { t: string; b: string }> = ${JSON.stringify(out)};\n`);
console.log(`embedded ${files.length} files, ${(bytes / 1024).toFixed(0)} KiB`);
